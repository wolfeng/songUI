import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const tokensPath = resolve(rootDir, 'src/tokens.json');
const distDir = resolve(rootDir, 'dist');

const tokens = JSON.parse(readFileSync(tokensPath, 'utf-8'));
mkdirSync(distDir, { recursive: true });

function renderCssVars(themeObj) {
  const lines = [];
  for (const [key, val] of Object.entries(themeObj.colors)) {
    const varName = key.startsWith('sundial-') ? `--${key}` : `--ses-${key}`;
    lines.push(`  ${varName}: ${val};`);
  }
  for (const [key, val] of Object.entries(themeObj.raw)) {
    lines.push(`  --ses-${key}: ${val};`);
  }
  return lines.join('\n');
}

// 1. Generate tokens.css
const [c1, c2, c3, c4] = tokens.motion.easeScroll;
const cssContent = `/* Generated by @song-ui/tokens — Do not edit manually */
:root, [data-theme="dark"] {
${renderCssVars(tokens.themes.dark)}
}

[data-theme="light"] {
${renderCssVars(tokens.themes.light)}
}

:root {
  --ses-ease-scroll: cubic-bezier(${c1}, ${c2}, ${c3}, ${c4});
  --ses-font-serif: ${tokens.typography.fontSerif};
  --ses-font-slender: ${tokens.typography.fontSlender};
  --ses-font-calligraphy: ${tokens.typography.fontCalligraphy};
  --ses-font-mono: ${tokens.typography.fontMono};
${Object.entries(tokens.typography.sizes).map(([k, v]) => `  --ses-text-${k}: ${v};`).join('\n')}
${Object.entries(tokens.typography.lineHeights).map(([k, v]) => `  --ses-leading-${k}: ${v};`).join('\n')}
${Object.entries(tokens.typography.tracking).map(([k, v]) => `  --ses-tracking-${k}: ${v};`).join('\n')}
${Object.entries(tokens.spacing).map(([k, v]) => `  --ses-space-${k}: ${v};`).join('\n')}
${Object.entries(tokens.radius).map(([k, v]) => `  --ses-radius-${k}: ${v};`).join('\n')}
${Object.entries(tokens.breakpoints).map(([k, v]) => `  --ses-bp-${k}: ${v};`).join('\n')}
}
`;
writeFileSync(resolve(distDir, 'tokens.css'), cssContent, 'utf-8');

// 2. Generate index.js & index.d.ts
const jsContent = `export const songTokens = ${JSON.stringify(tokens, null, 2)};\nexport default songTokens;\n`;
writeFileSync(resolve(distDir, 'index.js'), jsContent, 'utf-8');

const dtsContent = `export interface SongPaletteSwatch {
  id: string;
  name: string;
  hex: string;
  freq: number;
}

export interface SongThemeTokens {
  label: string;
  colors: Record<string, string>;
  raw: Record<string, string>;
}

export interface SongTokens {
  meta: {
    name: string;
    chineseName: string;
    version: string;
  };
  themes: {
    dark: SongThemeTokens;
    light: SongThemeTokens;
  };
  motion: {
    easeScroll: [number, number, number, number];
    durationFast: number;
    durationNormal: number;
    durationScroll: number;
  };
  typography: {
    fontSerif: string;
    fontSlender: string;
    fontCalligraphy: string;
    fontMono: string;
    sizes: Record<string, string>;
    lineHeights: Record<string, string>;
    tracking: Record<string, string>;
  };
  spacing: Record<string, string>;
  radius: Record<string, string>;
  breakpoints: Record<string, string>;
  paletteSwatches: SongPaletteSwatch[];
}

export declare const songTokens: SongTokens;
export default songTokens;
`;
writeFileSync(resolve(distDir, 'index.d.ts'), dtsContent, 'utf-8');

console.log('[@song-ui/tokens] Built tokens.css, index.js, and index.d.ts');
